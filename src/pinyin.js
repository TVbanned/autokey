// 构建单字符 → 首字母的快速查找 Map（仅初始化一次）
let _lookup = null
function getLookup() {
  if (_lookup) return _lookup
  _lookup = new Map()
  for (const [initial, chars] of Object.entries(_INITIAL_MAP)) {
    for (const ch of chars) {
      _lookup.set(ch, initial)
    }
  }
  return _lookup
}

/**
 * 取字符串的拼音首字母
 * 例如: getPinyinInitials('灰域信风') → 'hyxf'
 *       非中文字符保留原样
 */
export function getPinyinInitials(str) {
  const lookup = getLookup()
  let result = ''
  for (const ch of str) {
    result += lookup.get(ch) || ch.toLowerCase()
  }
  return result
}

/**
 * 检查搜索关键词是否匹配中文名称（支持拼音首字母）
 * @param {string} name - 中文名称
 * @param {string} keyword - 搜索关键词
 */
export function matchesSearch(name, keyword) {
  const kw = keyword.toLowerCase().trim()
  if (!kw) return true
  // 直接名称匹配
  if (name.toLowerCase().includes(kw)) return true
  // 拼音首字母匹配（仅当关键词全为字母时生效，避免中文输入中途误匹配）
  if (/^[a-z]+$/.test(kw)) {
    return getPinyinInitials(name).includes(kw)
  }
  return false
}
